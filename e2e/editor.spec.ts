    const canvas = document.createElement('canvas'); canvas.width = 800; canvas.height = 600
    canvas.getContext('2d')!.fillRect(0, 0, 800, 600)
    return new Promise<Blob>(resolve => canvas.toBlob(blob => resolve(blob!)))
