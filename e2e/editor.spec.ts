  const natural = await child.locator('img').evaluate(image => ({ width: (image as HTMLImageElement).naturalWidth, height: (image as HTMLImageElement).naturalHeight }))
  expect(natural).toEqual({ width: 800, height: 600 })
  await page.getByRole('tab', { name: 'Imagen', exact: true }).click()
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { read: () => Promise.reject(new DOMException('Denied', 'NotAllowedError')) } }))
